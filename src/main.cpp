                                        flute_notes.size() - song.motif_len;
                                    for (size_t k = 0; k < song.motif_len && hit; ++k) {
                                        const int v = flute_notes[off + k];
                                        hit = (v / 4 == song.motif[k]) && (v % 4 == 1);
                                    }
                                    if (!hit) continue;
