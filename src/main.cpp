                            const bool air = !dive && app.seat_air_w > 0.5f;
                            const bool run =
                                !dive && !air && app.run_w > 0.5f;
                            Vec3* off = dive  ? &app.seat_off_d
                                        : air ? &app.seat_off_a
                                        : run ? &app.seat_off_r
                                              : &app.seat_off_g;
