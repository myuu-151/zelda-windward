        glUniformMatrix4fv(sky_view, 1, GL_FALSE, view.m);
        glUniform1f(sky_aspect, aspect);
        glUniform1f(sky_tanfov, std::tan(25.0f * 3.14159265f / 180.0f));
        glUniform1f(sky_time, static_cast<float>(app.sim_time));
