    vec2 wxz = aPos + uCenter;
    vec2 uv = wxz * kWaveScale;
    float t = uTime * kWaveSpeed;
    float d1 = mod(uv.x + uv.y, M_2PI) + t * 0.07;
    float d2 = mod((uv.x + uv.y + 0.25) * 1.3, M_6PI) + t * 0.5;
    float lift = cos(d1) * 0.15 + cos(d2) * 0.05;
